"""Константы протокола IndexNow. Без Tkinter и сети - легко тестируются.

Источник: https://www.indexnow.org/documentation
"""
import re

# Ключ: 8-128 символов, только a-z, A-Z, 0-9 и дефис.
# Подчёркивание спецификацией НЕ допускается (в отличие от прежней версии
# приложения) - иначе движок отвечает 400/422.
KEY_PATTERN = re.compile(r"^[A-Za-z0-9-]{8,128}$")

KEY_RULE_TEXT = (
    "Ключ должен содержать от 8 до 128 символов и состоять только "
    "из латинских букв, цифр и дефисов ([A-Za-z0-9-])."
)

# Максимум URL в одном POST-запросе (ограничение протокола).
MAX_URLS_PER_REQUEST = 10_000

# Текст-заполнитель поля «Домен», который означает «не задано».
PLACEHOLDER_HOST = "example.com"

# Описания кодов ответа IndexNow.
STATUS_MESSAGES = {
    200: "OK. Страницы переданы на переиндексацию.",
    202: "Ключ принят и ожидает проверки. Отправьте ещё несколько адресов.",
    400: "Неверный формат запроса. Проверьте ключ, домен и ссылки.",
    403: "Неверный ключ. Проверьте ключ и расположение файла с ключом.",
    404: "Адрес приёмника не найден. Проверьте выбранный движок.",
    405: "Выбранный приёмник не поддерживает POST-запросы.",
    422: "Ошибка валидации: ссылки не принадлежат домену "
    "или ключ не соответствует схеме.",
    429: "Слишком много запросов. Подождите и повторите позже.",
    500: "Внутренняя ошибка на стороне приёмника. Повторите позже.",
    502: "Плохой шлюз на стороне приёмника. Повторите позже.",
    503: "Приёмник временно недоступен. Повторите позже.",
    504: "Приёмник не ответил вовремя. Повторите позже.",
}


def status_message(status: int, response_text: str = "") -> str:
    """Понятное описание HTTP-кода; для неизвестных - фрагмент ответа."""
    known = STATUS_MESSAGES.get(status)
    if known:
        return known
    snippet = " ".join((response_text or "").split())
    if len(snippet) > 300:
        snippet = snippet[:300] + "..."
    if snippet:
        return f"Ответ сервера: {snippet}"
    return "Неизвестный код ответа."


def is_success(status: int) -> bool:
    """True для 2xx - движок принял данные."""
    return 200 <= status < 300
